const {chromium}=require('playwright');
const fs=require('fs');
const os=require('os');
const path=require('path');
const assert=require('assert/strict');
const source=path.resolve(__dirname,'..');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'sirius-guide-alone-'));
 fs.copyFileSync(source+'/index.html',temp+'/index.html');
 const url='file://'+temp+'/index.html';const errors=[];
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 page.on('pageerror',e=>errors.push(e.message));await page.goto(url);
 await page.locator('[data-page="staging"]').click();
 await page.evaluate(()=>scrollTo(0,document.documentElement.scrollHeight));
 await page.locator('[data-page="overview"]').click();
 assert((await page.locator('#overview-title').boundingBox()).y<100,'Chapter reset scroll');
 await page.goBack();await page.waitForURL('**#staging');assert(await page.locator('#staging').isVisible(),'Back chapter');
 await page.goForward();await page.waitForURL('**#overview');assert(await page.locator('#overview').isVisible(),'Forward chapter');
 await page.goto(url+'#pr-1693');assert(await page.locator('#stacks').isVisible());assert.equal(await page.locator('#pr-1693').getAttribute('open'),'');
 await page.locator('#stack-filter').selectOption('Scan');await page.evaluate(()=>location.hash='#pr-1702');
 await page.locator('#pr-1702[open]').waitFor();assert.equal(await page.locator('#stack-filter').inputValue(),'all');
 await page.goto(url+'#package-P01');assert(await page.locator('#landing').isVisible());
 await page.locator('#package-P01 .pr-body a[href^="#reference-"]').click();
 assert(await page.locator('#references').isVisible());assert(await page.locator('#reference-pr-packages-p01-md[open]').isVisible());
 await page.goBack();await page.locator('#package-P01[open]').waitFor();
 await page.locator('[data-page="staging"]').click();
 await page.locator('a[href="#reference-research-staging-md"]').first().click();
 assert(await page.locator('#reference-research-staging-md[open]').isVisible());
 await page.locator('[data-page="overview"]').click();
 await page.locator('a[href="#reference-README-md"]').first().click();
 assert(await page.locator('#reference-README-md[open]').isVisible());
 const broken=await page.evaluate(()=>[...document.querySelectorAll('a[href]')].map(a=>a.getAttribute('href')).filter(h=>!h.startsWith('https://')&&!h.startsWith('#')));
 assert.deepEqual(broken,[],'No sibling-file links');
 const missing=await page.evaluate(()=>[...document.querySelectorAll('a[href^="#reference-"]')].map(a=>a.hash.slice(1)).filter(id=>!document.getElementById(id)));
 assert.deepEqual(missing,[],'All embedded reference links resolve');
 for(const [hash,chapter,text] of [['architecture-node-4','overview','CN exchange'],['stage-4','staging','Claim sequence']]){
  await page.goto(url+'#'+hash);assert(await page.locator('#'+chapter).isVisible());assert((await page.locator(hash.startsWith('stage')?'#stage-detail':'#architecture-detail').innerText()).includes(text));
 }
 const nojs=await browser.newPage({javaScriptEnabled:false,viewport:{width:736,height:900}});await nojs.goto(url);
 assert.equal(await nojs.locator('#pr-atlas details.pr-card').count(),19);assert.equal(await nojs.locator('#commit-rows tr').count(),59);
 await nojs.locator('[data-page="staging"]').click();assert(nojs.url().endsWith('#staging'));
 assert((await nojs.locator('#staging-title').boundingBox()).y<100,'Native chapter scroll');
 await nojs.goto(url+'#package-P01');await nojs.locator('#package-P01 summary').click();
 await nojs.locator('#package-P01 a[href^="#reference-"]').click();
 await nojs.locator('#reference-pr-packages-p01-md summary').click();
 assert(await nojs.locator('#reference-pr-packages-p01-md .reference-body').isVisible());
 const preview=await browser.newPage();await preview.setContent('<iframe sandbox="allow-scripts" style="width:100%;height:900px"></iframe>');
 await preview.locator('iframe').evaluate((f,html)=>f.srcdoc=html,fs.readFileSync(source+'/index.html','utf8'));
 const iframe=preview.frameLocator('iframe');await iframe.locator('body.enhanced').waitFor();
 await iframe.locator('[data-page="staging"]').click();assert(await iframe.locator('#staging').isVisible());
 await iframe.locator('a[href="#reference-research-staging-md"]').first().click();assert(await iframe.locator('#reference-research-staging-md[open]').isVisible());
 assert.deepEqual(errors,[]);
 fs.writeFileSync(source+'/research/navigation-validation.json',JSON.stringify({checkedAt:new Date().toISOString(),scenarios:['single HTML file with no sibling files','Back/Forward chapter history','chapter scroll reset','PR deep link after filters','package deep link and embedded source','embedded research and README links','diagram deep links','all 19 PRs and 59 commits without JavaScript','native navigation without JavaScript','sandboxed srcdoc preview navigation'],errors},null,2)+'\n');
 await browser.close();fs.rmSync(temp,{recursive:true,force:true});console.log('10 navigation scenarios passed; no missing internal links or page errors.');
})().catch(e=>{console.error(e);process.exit(1)});
